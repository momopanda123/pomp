const tables: Record<Locale, Record<MessageKey, string>> = { ko, en };

export type Translate = (key: MessageKey, params?: Record<string, string | number>) => string;

/** Picks the UI language from the host culture ("ko-KR"). Korean is the default when nothing is known. */
export function localeFromHost(locale: unknown): Locale {
  if (typeof locale !== 'string' || !locale) return 'ko';
  return locale.toLowerCase().startsWith('ko') ? 'ko' : 'en';
}

export function makeTranslate(locale: Locale): Translate {
  const table = tables[locale];
  return (key, params) => {
    const text = table[key] ?? key; // an unexpected key (e.g. from a newer host) degrades to its name instead of crashing
    if (!params) return text;
    return text.replace(/\{(\w+)\}/g, (match, name: string) => {
      const value = params[name];
      return value === undefined ? match : String(value);
    });
  };
}

export const LocaleContext = createContext<Locale>('ko');
export const useLocale = (): Locale => useContext(LocaleContext);

export const I18nContext = createContext<Translate>(makeTranslate('ko'));

/** Translation function for the current locale. */
export function useT(): Translate {
  return useContext(I18nContext);
}
