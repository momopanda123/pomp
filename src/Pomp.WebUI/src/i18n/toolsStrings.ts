export const toolsStrings = { ko, en };
export type ToolsStringKey = keyof typeof ko;
export type ToolsTranslate = (key: ToolsStringKey, params?: Record<string, string | number>) => string;
/** Local fallback until both shared i18n dictionaries spread toolsStrings. */
export function toolsTranslate(locale: string): ToolsTranslate {
  const table = locale.toLowerCase().startsWith('ko') ? toolsStrings.ko : toolsStrings.en;
  return (key, params) => table[key].replace(/\{(\w+)\}/g, (text, name: string) => params?.[name] === undefined ? text : String(params[name]));
}
