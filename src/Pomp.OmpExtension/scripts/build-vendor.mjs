// Reproducible offline-runtime dependencies. Run npm ci --ignore-scripts, then npm run build:vendor.
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
await build({ stdin: { contents: 'export { minimatch } from "minimatch"; export { parseDocument } from "yaml";', resolveDir: root },
  bundle: true, format: 'esm', platform: 'node', target: 'node18', outfile: path.join(root, 'vendor/rule-deps.mjs'), legalComments: 'inline' });
const packages = ['minimatch', 'brace-expansion', 'balanced-match', 'yaml'];
let notice = '# Bundled rule dependencies\n\nGenerated by scripts/build-vendor.mjs from pinned package-lock.json.\n';
for (const name of packages) {
 const dir = path.join(root, 'node_modules', name);
 const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
 const license = ['LICENSE', 'LICENSE.md', 'LICENSE-MIT'].find(f => fs.existsSync(path.join(dir, f)));
 if (!license) throw new Error('Missing license for ' + name);
 notice += '\n## ' + name + ' ' + pkg.version + '\n\n' + fs.readFileSync(path.join(dir, license), 'utf8') + '\n';
}
fs.writeFileSync(path.join(root, 'vendor/LICENSES.md'), notice);
