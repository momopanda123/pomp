using System;
using System.Collections.Generic;
using System.Text;
using System.Text.RegularExpressions;
using Pomp.Features;
using Pomp.Internal;

namespace Pomp.Hosting
{
    /// <summary>
    /// Writes the omp config overlay (<c>--config</c>) that pre-approves the host tools: omp treats tools without an approval
    /// declaration as "exec" and would prompt for every call under <c>--approval-mode always-ask</c>, but the pomp host
    /// gates its own tools (<c>PermissionGate</c>), so double prompts are avoided.
    /// </summary>
    internal static class OmpOverlayWriter
    {
        private static readonly Regex PlainKey = new Regex("^[A-Za-z_][A-Za-z0-9_.\\-]*$", RegexOptions.CultureInvariant);

        /// <summary>
        /// omp's <c>skills.*</c> switches for the folders of other programs, all written false: <c>~/.agents</c> and
        /// <c>&lt;project&gt;/.agents</c> (also <c>.agent</c>), <c>~/.claude</c> and <c>&lt;project&gt;/.claude</c>, and <c>~/.codex</c>.
        /// omp's own folders (<c>enablePiUser</c>/<c>enablePiProject</c>: <c>~/.omp/agent/skills</c> and <c>&lt;project&gt;/.omp/skills</c>)
        /// stay on, as do the custom directories below.
        /// </summary>
        private static readonly string[] OtherProgramSkillSources =
        {
            "enableAgentsUser", "enableAgentsProject", "enableClaudeUser", "enableClaudeProject", "enableCodexUser",
        };

        private static readonly HashSet<string> ReservedWords = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
        {
            "true", "false", "null", "yes", "no", "on", "off", "y", "n", "~",
        };

        /// <summary>
        /// The overlay text: <c>tools.approval.&lt;name&gt;: allow</c> for every host tool, and <c>deny</c> for
        /// <paramref name="deniedTools"/> (omp built-ins the user turned off; a user <c>deny</c> wins in every approval mode).
        /// A name in both lists stays allowed: host tools are gated by the host itself.
        /// With <paramref name="computer"/> (docs/architecture.md §8.5): omp's computer helpers start off (a conversation switches them on
        /// with <c>/computer on</c>), browser control follows the option but never runs with the network tools denied, and the computer
        /// helpers get <see cref="ComputerUse.ApprovalPolicy"/> (<paramref name="toolUi"/>: omp runs with <c>--mode rpc-ui</c>).
        /// With <paramref name="worktreeBase"/> (docs/architecture.md §8.11): task isolation is available, and an isolated task's changes
        /// stay a patch under that folder (never applied by omp) for the host to stage as change-review proposals.
        /// Always: <c>task.maxRecursionDepth: 1</c> (only the main agent spawns subagents; a subagent gets no <c>task</c> tool and its eval
        /// <c>agent()</c> fails with omp's depth message), and the other programs' skill folders are off (<see cref="OtherProgramSkillSources"/>).
        /// <paramref name="skillDirectories"/> and <paramref name="disabledExtensions"/> are the merged arrays: omp replaces arrays
        /// wholesale at each layer, so the overlay repeats the user's and the workspace's own values together with POMP's.
        /// </summary>
        public static string Build(IEnumerable<string> toolNames, IEnumerable<string>? deniedTools = null, ComputerUseOptions? computer = null, bool yolo = false, bool toolUi = false, IEnumerable<string>? skillDirectories = null, string? worktreeBase = null, IEnumerable<string>? disabledExtensions = null)
        {
            var text = new StringBuilder();
            text.Append("# Generated by pomp on every start. Do not edit: changes are overwritten.\n");
            var denied = new List<string>(deniedTools ?? Array.Empty<string>());
            if (computer != null)
            {
                text.Append("computer:\n  enabled: false\n");
                text.Append("browser:\n  enabled: ").Append(computer.Browser && !denied.Contains("browser") ? "true" : "false").Append('\n');
            }

            text.Append("task:\n  maxRecursionDepth: 1\n");
            if (worktreeBase != null)
            {
                text.Append("  isolation:\n    enabled: true\n    merge: patch\n    apply: false\n");
                text.Append("worktree:\n  base: ").Append(QuoteKey(worktreeBase)).Append('\n');
            }

            text.Append("skills:\n");
            foreach (var key in OtherProgramSkillSources) text.Append("  ").Append(key).Append(": false\n");
            if (skillDirectories != null)
            {
                text.Append("  customDirectories:\n");
                foreach (var directory in skillDirectories) text.Append("    - ").Append(QuoteKey(directory)).Append('\n');
            }

            if (disabledExtensions != null)
            {
                text.Append("disabledExtensions:\n");
                foreach (var entry in disabledExtensions) text.Append("  - ").Append(QuoteKey(entry)).Append('\n');
            }

            text.Append("tools:\n");
            var any = false;
            var seen = new HashSet<string>(StringComparer.Ordinal);
            void Add(string name, string policy)
            {
                if (string.IsNullOrEmpty(name) || !seen.Add(name))
                {
                    return;
                }

                if (!any)
                {
                    text.Append("  approval:\n");
                    any = true;
                }

                text.Append("    ").Append(QuoteKey(name)).Append(": ").Append(policy).Append('\n');
            }

            foreach (var name in toolNames)
            {
                Add(name, "allow");
            }

            foreach (var name in denied)
            {
                Add(name, "deny");
            }

            var computerPolicy = computer == null ? null : ComputerUse.ApprovalPolicy(computer, yolo, toolUi);
            if (computerPolicy != null) Add("computer", computerPolicy);
            // In yolo every other call runs unasked; browser actions still ask.
            if (computer != null && computer.Browser && yolo) Add("browser", "prompt");

            if (!any)
            {
                // omp requires a mapping at the root; keep the file valid even without tools.
                text.Append("  approval: {}\n");
            }

            return text.ToString();
        }

        public static void Write(string path, IEnumerable<string> toolNames, IEnumerable<string>? deniedTools = null, ComputerUseOptions? computer = null, bool yolo = false, bool toolUi = false, IEnumerable<string>? skillDirectories = null, string? worktreeBase = null, IEnumerable<string>? disabledExtensions = null) =>
            AtomicFile.WriteAllText(path, Build(toolNames, deniedTools, computer, yolo, toolUi, skillDirectories, worktreeBase, disabledExtensions));

        internal static string QuoteKey(string key)
        {
            if (PlainKey.IsMatch(key) && !ReservedWords.Contains(key))
            {
                return key;
            }

            var quoted = new StringBuilder("'");
            foreach (var c in key)
            {
                if (c == '\'')
                {
                    quoted.Append("''");
                }
                else if (c < ' ')
                {
                    // Control characters cannot appear in a single-quoted scalar; escape via a double-quoted form instead.
                    return DoubleQuote(key);
                }
                else
                {
                    quoted.Append(c);
                }
            }

            quoted.Append('\'');
            return quoted.ToString();
        }

        private static string DoubleQuote(string key)
        {
            var quoted = new StringBuilder("\"");
            foreach (var c in key)
            {
                switch (c)
                {
                    case '"':
                        quoted.Append("\\\"");
                        break;
                    case '\\':
                        quoted.Append("\\\\");
                        break;
                    case '\n':
                        quoted.Append("\\n");
                        break;
                    case '\r':
                        quoted.Append("\\r");
                        break;
                    case '\t':
                        quoted.Append("\\t");
                        break;
                    default:
                        if (c < ' ')
                        {
                            quoted.Append("\\u").Append(((int)c).ToString("x4"));
                        }
                        else
                        {
                            quoted.Append(c);
                        }

                        break;
                }
            }

            quoted.Append('"');
            return quoted.ToString();
        }
    }
}
